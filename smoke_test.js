const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");

const html = fs.readFileSync(path.join(__dirname, "index.html"), "utf8");
const dom = new JSDOM(html, { runScripts:"dangerously", resources:"usable", url:"http://localhost/", pretendToBeVisual:true });
const { window } = dom;
window.scrollTo = () => {};
window.AudioContext = function(){return {createOscillator:()=>({connect(){},start(){},stop(){},frequency:{}}),createGain:()=>({connect(){},gain:{exponentialRampToValueAtTime(){}}}),destination:{},currentTime:0};};
let failed=false;
window.addEventListener("error",e=>{failed=true;console.error("RUNTIME ERROR:",e.error?.stack||e.message);});
const scripts=["layouts.js","content.js","app.js"].map(f=>fs.readFileSync(path.join(__dirname,f),"utf8"));
window.eval(scripts.join("\n;\n"));
window.document.dispatchEvent(new window.Event("DOMContentLoaded",{bubbles:true,cancelable:true}));
const doc=window.document;
function check(label,condition){console.log((condition?"OK  ":"FAIL")+" - "+label);if(!condition)failed=true;}
check("onboarding screen active initially",doc.querySelector("#screen-onboarding").classList.contains("active"));
check("layout choices rendered",doc.querySelectorAll(".layout-card").length===3);
const choose=doc.querySelector(".layout-card .btn-primary");
check("Mangal layout can be selected",!!choose);
choose?.click();
check("home screen opens after selecting layout",doc.querySelector("#screen-home").classList.contains("active"));
check("course generated",window.app.chapters.length>10);
doc.querySelector("#nav-learn").click();
check("lesson list opens",doc.querySelector("#screen-learn-list").classList.contains("active"));
const first=doc.querySelector(".chapter-row");
check("lesson rows rendered",!!first);
first?.click();
check("lesson drill opens",doc.querySelector("#screen-learn-drill").classList.contains("active"));
check("lesson prompt is populated",doc.querySelector("#learn-prompt").textContent.length>0);
doc.querySelector("#nav-test").click();
check("test setup opens",doc.querySelector("#screen-test-setup").classList.contains("active"));
doc.querySelector("#test-start-btn").click();
check("test session starts",doc.querySelector("#screen-test-run").classList.contains("active"));
check("test passage has content",doc.querySelector("#test-source-text").textContent.length>20);
doc.querySelector("#test-quit-btn").click();
check("test results stored",JSON.parse(window.localStorage.getItem("devnagariTyping.v1")).history.length===1);
doc.querySelector("#nav-game").click();
check("game setup opens",doc.querySelector("#screen-game-setup").classList.contains("active"));
const game=doc.querySelector(".game-cat-btn");
check("game category buttons render",!!game);
game?.click();
check("game starts",doc.querySelector("#screen-game-run").classList.contains("active"));
check("game target is populated",doc.querySelector("#game-prompt").textContent.length>0);
window.clearInterval(window.app.game?.timer);
doc.querySelector("#nav-progress").click();
check("progress screen opens",doc.querySelector("#screen-progress").classList.contains("active"));
check("Devanagari grapheme grouping keeps matra with base",window.graphemeClusters("कि").length===1);
check("grapheme grouping preserves whole sample",window.graphemeClusters("हिंदी").join("")==="हिंदी");
console.log(failed?"\nSMOKE TEST: FAILURES DETECTED":"\nSMOKE TEST: ALL PASSED");
process.exitCode=failed?1:0;
